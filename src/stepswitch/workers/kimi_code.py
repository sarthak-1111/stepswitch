"""Kimi Code adapter (SPEC §12 item 6, ADR 0029): an ACP agent (`kimi acp`), the current
TypeScript CLI (the older Python packages are archived).

* **Model.** The `KIMI_MODEL_*` variables (read by `kimi acp` as by `kimi -p`) define the run's
  model without any file: the proxy's `/v1` base URL, the run's token as the key, the main slot
  as the model name, the endpoint's context window and an output cap within it (the harness
  otherwise asks for the whole remaining window).
* **Provider type.** `kimi` by default: chat-completions requests (`POST {base}/chat/completions`,
  a bearer key, streamed) with a few fields of its own (`thinking`, `prompt_cache_key`,
  `max_completion_tokens`) that the proxy reads or ignores. Its other values name API formats
  after their vendors, so a different one is set in local config
  (`[harness.kimi-code.env] KIMI_MODEL_PROVIDER_TYPE = "..."`), never in this repository.
* **Isolation.** `KIMI_CODE_HOME` is the run's own data directory, so the user's config,
  credentials, sessions and device ID are never read; its generated `config.toml` turns
  telemetry off and disables the web tools (search and URL fetch run without asking otherwise).
* **Egress.** Telemetry, the update preflight and scheduled jobs are off.
"""

from __future__ import annotations

from pathlib import Path

from stepswitch import tomlw
from stepswitch.workers.acp import AcpAdapter
from stepswitch.workers.harness import HarnessEndpoint, HarnessSettings, HarnessTask, model_id

PROVIDER_TYPE = "kimi"
# The harness's tools that reach the web (its tool reference).
WEB_TOOLS = ["WebSearch", "FetchURL"]
DEFAULT_OUTPUT = 16384


class KimiCodeAdapter(AcpAdapter):
    name = "kimi-code"
    title = "Kimi Code"
    binary = "kimi"
    support = "ACP agent (`kimi acp`), configured through KIMI_MODEL_* variables"
    offline_env = {
        "KIMI_DISABLE_TELEMETRY": "1",
        "KIMI_CODE_NO_AUTO_UPDATE": "1",
        "KIMI_DISABLE_CRON": "1",
    }
    acp_args = ("acp",)

    def model_value(self, endpoint: HarnessEndpoint) -> str:
        return model_id(endpoint.slot("main"))

    def environment(
        self,
        task: HarnessTask,
        workdir: Path,
        endpoint: HarnessEndpoint,
        settings: HarnessSettings,
    ) -> dict[str, str]:
        env = super().environment(task, workdir, endpoint, settings)
        output = min(DEFAULT_OUTPUT, endpoint.context // 4) if endpoint.context else DEFAULT_OUTPUT
        env.update(
            {
                "KIMI_MODEL_NAME": model_id(endpoint.slot("main")),
                "KIMI_MODEL_API_KEY": endpoint.token,
                "KIMI_MODEL_BASE_URL": endpoint.base_url + "/v1",
                "KIMI_MODEL_PROVIDER_TYPE": PROVIDER_TYPE,
                "KIMI_MODEL_MAX_COMPLETION_TOKENS": str(output),
            }
        )
        if endpoint.context:
            env["KIMI_MODEL_MAX_CONTEXT_SIZE"] = str(endpoint.context)
        if settings.state_dir is not None:
            home = settings.state_dir / "kimi-home"
            home.mkdir(parents=True, exist_ok=True)
            config = {"telemetry": False, "tools": {"disabled": WEB_TOOLS}}
            (home / "config.toml").write_text(
                tomlw.dumps(config, header="# Generated by Stepswitch for one harness run."),
                encoding="utf-8",
            )
            env["KIMI_CODE_HOME"] = str(home)
        return env
