"""The compatibility matrix (SPEC §4.7): `docs/COMPATIBILITY.md`, generated from probe results.

Probe results are the files `ssw probe --export` writes (`stepswitch.compat.probe.export`).
In a source checkout they live in `probes/`: `ssw probe --ci-set` writes one per model of the
CI model set (`probes/ci-set.yaml`), and anyone can add a result for another model or engine by
pull request. `ssw probe --render-matrix` renders the matrix from every result there and
`--check` fails when the committed file is out of date, so the matrix lists exactly what has
been verified and nothing else (SPEC §4.8).

A model passes the probe suite when the checks the built-in agent depends on pass: basic chat,
system-prompt adherence, usage reporting and format detection, plus one way to call tools,
natively or through the fallback protocol (ADR 0021). The other checks describe capabilities
that the router reads; a "no" there is not a failure.
"""

from __future__ import annotations

import json
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from stepswitch.compat import probe

RESULTS_DIR = "probes"
CI_SET_FILE = "ci-set.yaml"
MATRIX_FILE = "docs/COMPATIBILITY.md"
GENERATED_MARKER = "generated by `ssw probe --render-matrix`"
REQUIRED_CHECKS: tuple[str, ...] = ("basic_chat", "system_prompt", "usage", "formats_served")
TOOL_PATHS: tuple[tuple[str, str], ...] = (
    ("native_tool_call", "native"),
    ("fallback_tool_protocol", "fallback"),
)
CHECK_LABELS = {
    "basic_chat": "basic chat",
    "system_prompt": "system prompt",
    "native_tool_call": "native tool call",
    "parallel_tool_calls": "parallel tool calls",
    "fallback_tool_protocol": "fallback tool protocol",
    "json_schema": "JSON Schema output",
    "streaming": "streaming",
    "usage": "usage reporting",
    "reasoning_field": "reasoning field",
    "context_length": "context length",
    "prefix_cache": "prefix cache",
    "throughput": "throughput",
    "tool_call_ids": "tool-call IDs",
    "forced_tool_choice": "forced tool choice",
    "assistant_prefill": "assistant prefill",
    "streamed_tool_args": "streamed tool arguments",
    "structured_output_under_reasoning": "structured output with reasoning",
    "reasoning_retention": "reasoning retention",
    "usage_semantics": "usage semantics",
    "formats_served": "formats served",
}
SHOWN = {True: "yes", False: "no", None: "skipped"}


class MatrixError(ValueError):
    pass


@dataclass(frozen=True)
class ProbeResult:
    path: Path
    model: str
    engine: str | None
    engine_version: str | None
    format: str | None
    date: str | None
    quick: bool
    model_hash: str | None
    hardware: dict[str, Any] = field(default_factory=dict)
    checks: dict[str, dict[str, Any]] = field(default_factory=dict)

    def ok(self, check: str) -> bool | None:
        value = (self.checks.get(check) or {}).get("ok")
        return value if isinstance(value, bool) else None


@dataclass(frozen=True)
class Verdict:
    passed: bool
    failed: list[str]
    tool_path: str | None


@dataclass(frozen=True)
class CiSet:
    engine: str
    models: list[str]


def results_dir(root: Path) -> Path:
    return root / RESULTS_DIR


def load_ci_set(root: Path) -> CiSet:
    path = results_dir(root) / CI_SET_FILE
    data = YAML(typ="safe", pure=True).load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict) or data.get("schema") != 1:
        raise MatrixError(f"{path.name}: expected `schema: 1`")
    models = data.get("models")
    if not isinstance(models, list) or not models or not all(isinstance(m, str) for m in models):
        raise MatrixError(f"{path.name}: `models` must be a list of registry ids")
    return CiSet(engine=str(data.get("engine") or "llamacpp"), models=list(models))


def load_result(path: Path) -> ProbeResult:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or data.get("kind") != probe.EXPORT_KIND:
        raise MatrixError(f"{path.name}: not a probe result (kind {probe.EXPORT_KIND!r})")
    if data.get("schema") != probe.SCHEMA:
        raise MatrixError(f"{path.name}: unsupported schema {data.get('schema')!r}")
    if not isinstance(data.get("model"), str) or not isinstance(data.get("checks"), dict):
        raise MatrixError(f"{path.name}: a result needs `model` and `checks`")
    return ProbeResult(
        path=path,
        model=data["model"],
        engine=data.get("engine"),
        engine_version=data.get("engine_version"),
        format=data.get("format"),
        date=data.get("date"),
        quick=bool(data.get("quick")),
        model_hash=data.get("model_hash"),
        hardware=dict(data.get("hardware") or {}),
        checks={k: dict(v) for k, v in data["checks"].items() if isinstance(v, dict)},
    )


def load_results(root: Path) -> list[ProbeResult]:
    """Every probe result in `probes/`, by file name."""
    folder = results_dir(root)
    if not folder.is_dir():
        return []
    return [load_result(path) for path in sorted(folder.glob("*.json"))]


def verdict(result: ProbeResult) -> Verdict:
    """Whether the result passes the probe suite (ADR 0021)."""
    failed = [check for check in REQUIRED_CHECKS if result.ok(check) is not True]
    tool_path = next((label for check, label in TOOL_PATHS if result.ok(check) is True), None)
    if tool_path is None:
        failed.append("tool calls")
    if result.quick:
        failed.append("full probe")
    return Verdict(passed=not failed, failed=failed, tool_path=tool_path)


def result_name(model: str, engine: str) -> str:
    return f"{probe.safe_model_name(model)}--{engine}.json"


# --------------------------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------------------------


def _ordered(results: Sequence[ProbeResult], ci_models: Sequence[str]) -> list[ProbeResult]:
    rank = {model: index for index, model in enumerate(ci_models)}
    return sorted(results, key=lambda r: (rank.get(r.model, len(rank)), r.model, r.path.name))


def _engine_text(result: ProbeResult) -> str:
    return " ".join(part for part in (result.engine, result.engine_version) if part) or "-"


def _hardware_text(hardware: Mapping[str, Any]) -> list[str]:
    system = hardware.get("os") or {}
    cpu = hardware.get("cpu") or {}
    gpus = [gpu for gpu in hardware.get("gpus") or [] if isinstance(gpu, dict)]
    memory = ", ".join(f"{gpu.get('vram_gb')} GB" for gpu in gpus if gpu.get("vram_gb"))
    return [
        str(system.get("system") or "-"),
        str(system.get("machine") or "-"),
        str(cpu.get("cores_logical") or "-"),
        str(hardware.get("ram_gb") or "-"),
        f"{len(gpus)} ({memory})" if memory else str(len(gpus)),
    ]


def render(root: Path) -> str:
    """The text of `docs/COMPATIBILITY.md` for the results in `probes/`."""
    from stepswitch import registry

    entries = registry.load()
    try:
        ci_models = load_ci_set(root).models
    except (OSError, MatrixError):
        ci_models = []
    results = _ordered(load_results(root), ci_models)
    lines = [
        "# Compatibility matrix",
        "",
        f"<!-- {GENERATED_MARKER} from the probe results in probes/; do not edit -->",
        "",
        "This page lists exactly what has been verified: one column per probe result in",
        "[`probes/`](../probes/). Results for the CI model set (`probes/ci-set.yaml`) come from",
        "`ssw probe --ci-set`. To add a result for another model or engine, run",
        "`ssw probe <endpoint> --model <model> --export probes/<model>--<engine>.json` and open a",
        "pull request.",
        "",
        "A model passes the probe suite when basic chat, system-prompt adherence, usage reporting",
        "and format detection work, and it can call tools natively or through the fallback tool",
        'protocol (ADR 0021). The other checks describe capabilities the router uses; a "no"',
        "there is not a failure.",
        "",
        "## Models",
        "",
        "| Model | Family | Engine | Format | Probe suite | Tool calls | Result | Date |",
        "|---|---|---|---|---|---|---|---|",
    ]
    if not results:
        lines.append("| _no probe results yet_ | | | | | | | |")
    for result in results:
        entry = entries.get(result.model)
        outcome = verdict(result)
        suite = "passes" if outcome.passed else "fails: " + ", ".join(outcome.failed)
        lines.append(
            f"| {result.model} | {entry.family if entry and entry.family else '-'}"
            f" | {_engine_text(result)} | {result.format or '-'} | {suite}"
            f" | {outcome.tool_path or 'none'} | `{result.path.name}` | {result.date or '-'} |"
        )
    if results:
        lines += ["", "## Checks", ""]
        lines.append("| Check | " + " | ".join(r.model for r in results) + " |")
        lines.append("|---|" + "---|" * len(results))
        for check in probe.CHECKS:
            label = CHECK_LABELS.get(check, check)
            lines.append(f"| {label} | " + " | ".join(SHOWN[r.ok(check)] for r in results) + " |")
        lines += [
            "",
            '"skipped" means the check did not apply or was not run.',
            "",
            "## Hardware",
            "",
            "| Result | OS | Architecture | CPU threads | RAM (GB) | GPUs |",
            "|---|---|---|---|---|---|",
        ]
        for result in results:
            cells = _hardware_text(result.hardware)
            lines.append(f"| `{result.path.name}` | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def write(root: Path) -> Path:
    path = root / MATRIX_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(root), encoding="utf-8", newline="\n")
    return path


def is_current(root: Path) -> bool:
    path = root / MATRIX_FILE
    return path.is_file() and path.read_text(encoding="utf-8") == render(root)


# --------------------------------------------------------------------------------------------
# Probing the CI model set
# --------------------------------------------------------------------------------------------


def probe_ci_set(
    root: Path,
    *,
    config: Any = None,
    egress: Any = None,
    models: Sequence[str] | None = None,
    echo: Callable[[str], None] = print,
) -> list[Path]:
    """Probe every model of the CI model set on a managed server; write its result to
    `probes/`. Each server is stopped after its probe."""
    from stepswitch import config as config_module
    from stepswitch import doctor
    from stepswitch.config import EndpointConfig
    from stepswitch.serve.manager import ServerManager

    config = config or config_module.load(root)
    ci_set = load_ci_set(root)
    hardware = doctor.collect(models_dir=config.models_dir(), egress=egress)
    manager = ServerManager(root, config)
    written = []
    for model in models or ci_set.models:
        info = manager.ensure(model, engine=ci_set.engine)
        try:
            endpoint = EndpointConfig(
                name="managed",
                url=info.base_url,
                engine=ci_set.engine,
                format="chat-completions",
                auth="bearer" if info.api_key else "none",
                api_key=info.api_key,
                models=[info.engine_model or model],
                local=True,
            )
            profile = probe.run(
                endpoint, model=info.engine_model or model, egress=egress, echo=echo
            )
            profile["model"] = model
            path = results_dir(root) / result_name(model, ci_set.engine)
            written.append(probe.export(profile, path, hardware=hardware))
        finally:
            manager.stop(model)
    return written
