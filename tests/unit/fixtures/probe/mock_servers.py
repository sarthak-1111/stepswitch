class ChatServer:
    """chat-completions mock: `GET /v1/models`, `GET /health`, `POST /v1/chat/completions`."""

    def __init__(
        self,
        brain: Brain | None = None,
        *,
        model_id: str = "mock-model",
        meta: dict[str, Any] | None = None,
        ids: bool = True,
        stream_usage: bool = True,
        reasoning_field: str = "reasoning_content",
        fail: frozenset[str] = frozenset(),
        key: str | None = None,
        calls_as_text: bool = False,
    ) -> None:
        self.brain = brain or Brain()
        self.model_id = model_id
        # Tool calls come back as a bare JSON list in the text, the way the llama.cpp server
        # returns Granite-3.3 calls (docs/RESEARCH.md): no `tool_calls`, finish reason `stop`.
        self.calls_as_text = calls_as_text
        self.meta = meta
        self.ids = ids
        self.stream_usage = stream_usage
        self.reasoning_field = reasoning_field
        self.fail = fail
        self.key = key
        self.calls = 0
        self.mock = MockServer()
        self.mock.route("GET", r"/v1/models", self.models)
        self.mock.route("GET", r"/health", lambda _r: json_response({"status": "ok"}))
        self.mock.route("POST", r"/v1/chat/completions", self.chat)

    def transport(self) -> httpx.MockTransport:
        return self.mock.transport()

    @property
    def chats(self) -> list[Recorded]:
        return [r for r in self.mock.requests if r.path.endswith("/chat/completions")]

    def models(self, _recorded: Recorded) -> httpx.Response:
        entry: dict[str, Any] = {"id": self.model_id, "object": "model", "owned_by": "mock"}
        if self.meta is not None:
            entry["meta"] = self.meta
        return json_response({"object": "list", "data": [entry]})

    @staticmethod
    def _neutral(message: dict[str, Any]) -> dict[str, Any]:
        content = message.get("content")
        if isinstance(content, list):
            content = "".join(part.get("text", "") for part in content)
        return {
            "role": message["role"],
            "content": content or "",
            "calls": message.get("tool_calls") or [],
            "reasoning": message.get("reasoning_content") or message.get("reasoning"),
        }

    def chat(self, recorded: Recorded) -> httpx.Response:
        body = recorded.body
        if self.key and recorded.headers.get("authorization") != f"Bearer {self.key}":
            return json_response({"error": {"message": "bad key", "type": "auth_error"}}, 401)
        messages = [self._neutral(message) for message in body["messages"]]
        tools = [tool["function"]["name"] for tool in body.get("tools") or []]
        choice = body.get("tool_choice")
        forced = choice["function"]["name"] if isinstance(choice, dict) else None
        response_format = body.get("response_format") or {}
        schema = None
        if response_format.get("type") == "json_schema":
            schema = response_format["json_schema"]["name"]
        if schema == "city_facts" and "schema" in self.fail:
            message = f"upstream failure at {BASE_URL}/x with key {KEY} under {Path.home()}"
            return json_response({"error": {"message": message, "type": "server_error"}}, 500)
        prompt = self.brain.prompt(messages, body.get("tools") or [])
        tokens, cached, truncated = self.brain.count(prompt)
        reply = self.brain.reply(messages, tools, forced, schema, truncated)
        if self.calls_as_text and reply.calls:
            listed = [{"arguments": args, "name": name} for name, args in reply.calls]
            reply = Reply(text=json.dumps(listed), reasoning=reply.reasoning)
        reply, completion, cut = _limit(reply, int(body.get("max_tokens") or 10**6))
        usage = {
            "prompt_tokens": tokens,
            "completion_tokens": completion,
            "total_tokens": tokens + completion,
            "prompt_tokens_details": {"cached_tokens": cached},
        }
        finish = "tool_calls" if reply.calls else ("length" if cut else "stop")
        wire_calls = [
            self._call(index, name, args) for index, (name, args) in enumerate(reply.calls)
        ]
        if body.get("stream"):
            include = (body.get("stream_options") or {}).get("include_usage")
            return sse_response(self._chunks(reply, wire_calls, finish, usage if include else None))
        message_out: dict[str, Any] = {
            "role": "assistant",
            "content": reply.text or (None if wire_calls else ""),
        }
        if reply.reasoning:
            message_out[self.reasoning_field] = reply.reasoning
        if wire_calls:
            message_out["tool_calls"] = wire_calls
        return json_response(
            {
                "id": "chatcmpl-mock",
                "object": "chat.completion",
                "created": 1,
                "model": self.model_id,
                "choices": [{"index": 0, "message": message_out, "finish_reason": finish}],
                "usage": usage,
            }
        )

    def _call(self, index: int, name: str, args: dict[str, Any]) -> dict[str, Any]:
        self.calls += 1
        call: dict[str, Any] = {
            "index": index,
            "type": "function",
            "function": {"name": name, "arguments": json.dumps(args)},
        }
        if self.ids:
            call["id"] = f"call_{self.calls:04d}"
        return call

    def _chunks(
        self,
        reply: Reply,
        calls: list[dict[str, Any]],
        finish: str,
        usage: dict[str, Any] | None,
    ) -> Iterator[dict[str, Any] | str]:
        base = {
            "id": "chatcmpl-mock",
            "object": "chat.completion.chunk",
            "created": 1,
            "model": self.model_id,
        }

        def delta(payload: dict[str, Any], reason: str | None = None) -> dict[str, Any]:
            return {**base, "choices": [{"index": 0, "delta": payload, "finish_reason": reason}]}

        yield delta({"role": "assistant", "content": ""})
        if reply.reasoning:
            yield delta({self.reasoning_field: reply.reasoning})
        for piece in _pieces(reply.text, 6) if reply.text else []:
            yield delta({"content": piece})
        for call in calls:
            head = {
                "index": call["index"],
                "type": "function",
                "function": {"name": call["function"]["name"], "arguments": ""},
            }
            if "id" in call:
                head["id"] = call["id"]
            yield delta({"tool_calls": [head]})
            for piece in _pieces(call["function"]["arguments"], 5):
                fragment = {"index": call["index"], "function": {"arguments": piece}}
                yield delta({"tool_calls": [fragment]})
        yield delta({}, finish)
        if usage is not None and self.stream_usage:
            yield {**base, "choices": [], "usage": usage}
        yield "[DONE]"


