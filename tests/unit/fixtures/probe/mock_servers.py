class OllamaServer:
    """Ollama native mock: version, tags, ps, show, /v1/models and `POST /api/chat`."""

    MODEL = "mock:latest"

    def __init__(self, brain: Brain | None = None, *, loaded: int | None = 8192) -> None:
        self.brain = brain or Brain()
        self.loaded = loaded
        self.mock = MockServer()
        self.mock.route("GET", r"/api/version", lambda _r: json_response({"version": "0.34.4"}))
        self.mock.route("GET", r"/api/tags", self.tags)
        self.mock.route("GET", r"/api/ps", self.ps)
        self.mock.route("POST", r"/api/show", self.show)
        self.mock.route("GET", r"/v1/models", self.models)
        self.mock.route("POST", r"/api/chat", self.chat)

    def transport(self) -> httpx.MockTransport:
        return self.mock.transport()

    @property
    def chats(self) -> list[Recorded]:
        return [r for r in self.mock.requests if r.path == "/api/chat"]

    def tags(self, _recorded: Recorded) -> httpx.Response:
        local = {
            "name": self.MODEL,
            "model": self.MODEL,
            "digest": DIGEST,
            "size": 1234,
            "details": {"family": "qwen2", "context_length": 32768},
            "capabilities": ["completion", "tools"],
        }
        remote = {"name": "cloudy:latest", "model": "cloudy:latest", "remote_host": "x"}
        return json_response({"models": [remote, local]})

    def ps(self, _recorded: Recorded) -> httpx.Response:
        if self.loaded is None:
            return json_response({"models": []})
        return json_response({"models": [{"name": self.MODEL, "context_length": self.loaded}]})

    def show(self, _recorded: Recorded) -> httpx.Response:
        return json_response(
            {
                "modelfile": f"FROM {Path.home() / 'blobs' / 'sha256-0000'}",
                "parameters": "num_ctx                        4096\ntemperature 0.7",
                "template": "{{ .Prompt }}",
                "license": "a license text",
                "details": {
                    "family": "qwen2",
                    "parameter_size": "1.5B",
                    "quantization_level": "Q4",
                },
                "model_info": {"general.architecture": "qwen2", "qwen2.context_length": 32768},
                "capabilities": ["completion", "tools"],
            }
        )

    def models(self, _recorded: Recorded) -> httpx.Response:
        return json_response({"object": "list", "data": [{"id": self.MODEL, "object": "model"}]})

    @staticmethod
    def _neutral(message: dict[str, Any]) -> dict[str, Any]:
        return {
            "role": message["role"],
            "content": message.get("content") or "",
            "calls": message.get("tool_calls") or [],
            "reasoning": message.get("thinking"),
        }

    def chat(self, recorded: Recorded) -> httpx.Response:
        body = recorded.body
        messages = [self._neutral(message) for message in body["messages"]]
        tools = [tool["function"]["name"] for tool in body.get("tools") or []]
        fmt = body.get("format")
        schema = None
        if isinstance(fmt, dict):
            schema = "action" if "anyOf" in fmt else "city_facts"
        prompt = self.brain.prompt(messages, body.get("tools") or [])
        tokens, cached, truncated = self.brain.count(prompt)
        reply = self.brain.reply(messages, tools, None, schema, truncated)
        options = body.get("options") or {}
        reply, completion, cut = _limit(reply, int(options.get("num_predict") or 10**6))
        message: dict[str, Any] = {"role": "assistant", "content": reply.text}
        if reply.reasoning:
            message["thinking"] = reply.reasoning
        if reply.calls:
            message["tool_calls"] = [
                {
                    "id": f"call_{index}",
                    "function": {"index": index, "name": name, "arguments": args},
                }
                for index, (name, args) in enumerate(reply.calls)
            ]
        final = {
            "model": self.MODEL,
            "created_at": "2026-10-16T00:00:00Z",
            "done": True,
            "done_reason": "length" if cut else "stop",
            "total_duration": 9_000_000,
            "load_duration": 1_000,
            "prompt_eval_count": tokens,
            "prompt_eval_cached_count": cached,
            # 1000 prompt tokens per second, 50 generated tokens per second.
            "prompt_eval_duration": max(1, tokens - cached) * 1_000_000,
            "eval_count": completion,
            "eval_duration": completion * 20_000_000,
        }
        if not body.get("stream"):
            return json_response({**final, "message": message})
        lines: list[dict[str, Any]] = []
        if reply.reasoning:
            lines.append(
                {
                    "model": self.MODEL,
                    "message": {"role": "assistant", "content": "", "thinking": reply.reasoning},
                    "done": False,
                }
            )
        for piece in _pieces(reply.text, 6) if reply.text else []:
            lines.append(
                {
                    "model": self.MODEL,
                    "message": {"role": "assistant", "content": piece},
                    "done": False,
                }
            )
        if reply.calls:
            lines.append(
                {
                    "model": self.MODEL,
                    "message": {**message, "content": "", "thinking": None},
                    "done": False,
                }
            )
        lines.append({**final, "message": {"role": "assistant", "content": ""}})
        return ndjson_response(lines)


