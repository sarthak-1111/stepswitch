"""Shared machinery for the per-format conformance suites (claim C-004).

Each `tests/conformance/test_<format>.py` defines `SUITE = FormatSuite(...)` whose cases run a
codec through `ModelClient` against an in-process mock server for that format. The pytest tests
in each file run the cases one by one; the C-004 claim test runs every suite and writes the
evidence. Every suite must provide the cases in `REQUIRED_CASES`.

Mock responses follow the format references cited in docs/RESEARCH.md ("API formats"). They
are written by hand from those references, never generated by the codec under test.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable, Iterable
from dataclasses import dataclass, field
from typing import Any

import httpx

from stepswitch.compat.client import Endpoint, ModelClient
from stepswitch.compat.codecs.base import CodecOptions
from stepswitch.compat.framing import StreamEvent, format_ndjson, format_sse
from stepswitch.compat.ir import (
    Message,
    Request,
    ResponseFormat,
    TextPart,
    ToolCallPart,
    ToolResultPart,
    ToolSpec,
)

REQUIRED_CASES = (
    "non-streaming",
    "streaming",
    "tool-call",
    "parallel-tool-calls",
    "error",
    "usage",
)

# --------------------------------------------------------------------------------------------
# Mock server
# --------------------------------------------------------------------------------------------


@dataclass
class Recorded:
    method: str
    path: str
    headers: dict[str, str]
    body: Any
    params: dict[str, str]


Responder = Callable[[Recorded], httpx.Response]


@dataclass
class MockServer:
    """Routes (method, path regex) to responders and records every request it receives."""

    routes: list[tuple[str, re.Pattern[str], Responder]] = field(default_factory=list)
    requests: list[Recorded] = field(default_factory=list)

    def route(self, method: str, path_regex: str, responder: Responder) -> MockServer:
        self.routes.append((method.upper(), re.compile(path_regex), responder))
        return self

    def _handle(self, request: httpx.Request) -> httpx.Response:
        try:
            body: Any = json.loads(request.content) if request.content else None
        except json.JSONDecodeError:
            body = request.content.decode("utf-8", "replace")
        recorded = Recorded(
            method=request.method,
            path=request.url.path,
            headers={k.lower(): v for k, v in request.headers.items()},
            body=body,
            params=dict(request.url.params),
        )
        self.requests.append(recorded)
        for method, pattern, responder in self.routes:
            if method == request.method and pattern.fullmatch(request.url.path):
                return responder(recorded)
        return httpx.Response(
            404, json={"error": {"message": f"no mock route for {request.url.path}"}}
        )

    def transport(self) -> httpx.MockTransport:
        return httpx.MockTransport(self._handle)

    @property
    def last(self) -> Recorded:
        assert self.requests, "the mock server received no request"
        return self.requests[-1]


def json_response(
    payload: Any, status: int = 200, headers: dict[str, str] | None = None
) -> httpx.Response:
    return httpx.Response(status, json=payload, headers=headers)


def sse_response(
    events: Iterable[StreamEvent | dict[str, Any] | str], status: int = 200
) -> httpx.Response:
    """SSE body from events; dicts become `data: <json>`, strings are sent as raw data."""
    chunks = []
    for event in events:
        if isinstance(event, dict):
            event = StreamEvent(data=json.dumps(event))
        elif isinstance(event, str):
            event = StreamEvent(data=event)
        chunks.append(format_sse(event))
    return httpx.Response(
        status, content="".join(chunks).encode(), headers={"content-type": "text/event-stream"}
    )


def ndjson_response(lines: Iterable[dict[str, Any]], status: int = 200) -> httpx.Response:
    body = "".join(format_ndjson(StreamEvent(data=json.dumps(line))) for line in lines)
    return httpx.Response(
        status, content=body.encode(), headers={"content-type": "application/x-ndjson"}
    )


def client_for(
    fmt: str, server: MockServer, *, model: str = "test-model", options: CodecOptions | None = None
) -> ModelClient:
    endpoint = Endpoint(
        name="mock",
        base_url="http://127.0.0.1:65530",
        format=fmt,
        model=model,
        options=options or CodecOptions(),
    )
    return ModelClient(endpoint, transport=server.transport(), max_retries=0, sleep=lambda _s: None)


