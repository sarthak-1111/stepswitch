ANSWER = "Hello there."

WEATHER = ToolSpec(
    name="get_weather",
    description="Get the current weather for a city.",
    parameters={
        "type": "object",
        "properties": {"city": {"type": "string"}, "unit": {"type": "string", "enum": ["c", "f"]}},
        "required": ["city"],
    },
)
CLOCK = ToolSpec(
    name="get_time",
    description="Get the local time in a city.",
    parameters={"type": "object", "properties": {"city": {"type": "string"}}, "required": ["city"]},
)


def text_request(model: str = "test-model") -> Request:
    return Request(
        model=model,
        system=[TextPart(text="You are terse.")],
        messages=[Message.text("user", "Say hello.")],
        max_output_tokens=64,
    )


def tool_request(model: str = "test-model") -> Request:
    return Request(
        model=model,
        system=[TextPart(text="Use tools when needed.")],
        messages=[Message.text("user", "Weather in Paris and time in Tokyo?")],
        tools=[WEATHER, CLOCK],
        tool_choice="auto",
        max_output_tokens=128,
    )


def conversation_request(model: str = "test-model") -> Request:
    """A full tool loop: user -> two parallel calls -> two results -> answer -> follow-up."""
    return Request(
        model=model,
        system=[TextPart(text="Use tools when needed.")],
        messages=[
            Message.text("user", "Weather in Paris and time in Tokyo?"),
            Message(
                role="assistant",
                content=[
                    ToolCallPart(id="call_a", name="get_weather", arguments='{"city":"Paris"}'),
                    ToolCallPart(id="call_b", name="get_time", arguments='{"city":"Tokyo"}'),
                ],
            ),
            Message(
                role="tool",
                content=[
                    ToolResultPart(
                        call_id="call_a", name="get_weather", content=[TextPart(text="18 C, sunny")]
                    )
                ],
            ),
            Message(
                role="tool",
                content=[
                    ToolResultPart(
                        call_id="call_b", name="get_time", content=[TextPart(text="21:04")]
                    )
                ],
            ),
            Message.text("assistant", "Paris is 18 C and sunny; it is 21:04 in Tokyo."),
            Message.text("user", "Thanks. Answer in JSON next time."),
        ],
        tools=[WEATHER, CLOCK],
        response_format=ResponseFormat(
            type="json_schema",
            name="answer",
            json_schema={"type": "object", "properties": {"answer": {"type": "string"}}},
        ),
        max_output_tokens=256,
    )


# --------------------------------------------------------------------------------------------
# Normalization for round-trip comparisons (lossless scope, ADR 0003 item 3)
# --------------------------------------------------------------------------------------------


def normalize(request: Request) -> dict[str, Any]:
    """Format-independent view of a request: system text, messages, tools.

    Tool-call IDs are replaced by their order of appearance, since some formats carry no IDs and
    synthesize them; what must survive is which result answers which call. Consecutive tool
    messages are merged, since formats group results differently.
    """
    ids: dict[str, str] = {}

    def label(call_id: str) -> str:
        return ids.setdefault(call_id, f"#{len(ids)}")

    system = [p.text for p in request.system]
    messages: list[dict[str, Any]] = []
    for message in request.messages:
        if message.role == "system":
            system.append(message.text_content())
            continue
        parts: list[Any] = []
        for part in message.content:
            if isinstance(part, TextPart):
                parts.append(("text", part.text))
            elif isinstance(part, ToolCallPart):
                parts.append(
                    ("call", label(part.id), part.name, json.loads(part.arguments or "{}"))
                )
            elif isinstance(part, ToolResultPart):
                parts.append(("result", label(part.call_id), part.text()))
        role = message.role
        if messages and role == "tool" and messages[-1]["role"] == "tool":
            messages[-1]["parts"].extend(parts)
        else:
            messages.append({"role": role, "parts": parts})
    tools = [(t.name, t.description or "", t.parameters) for t in request.tools]
    return {"system": "\n\n".join(s for s in system if s), "messages": messages, "tools": tools}


# --------------------------------------------------------------------------------------------
# Suites
# --------------------------------------------------------------------------------------------


@dataclass
class FormatSuite:
    format: str
    cases: dict[str, Callable[[], None]]

    def missing_cases(self) -> list[str]:
        return [case for case in REQUIRED_CASES if case not in self.cases]


def run_suite(suite: FormatSuite) -> dict[str, str]:
    results: dict[str, str] = {}
    for name, case in suite.cases.items():
        try:
            case()
        except Exception as exc:  # noqa: BLE001 - a case result is pass or a reason
            results[name] = f"failed: {type(exc).__name__}: {exc}"[:500]
        else:
            results[name] = "passed"
    for name in suite.missing_cases():
        results[name] = "failed: case missing"
    return results
